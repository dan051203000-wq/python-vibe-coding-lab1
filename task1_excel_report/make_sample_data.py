"""生成含脏数据的样例 sales_raw.xlsx，用于考题一的本地验证。

内置脏数据形态：
- 3 行关键字段空值（日期/销售员/单价缺失各一行）
- 2 行完全重复（与正常行 6 列全同）
- 2 行数量为负、1 行数量为 0
- 1 行数量为非数值文本
"""
from pathlib import Path

import pandas as pd

COLUMNS = ["日期", "销售员", "产品", "数量", "单价", "地区"]

GOOD_ROWS = [
    ("2026-10-01", "张三", "机械键盘", 3, 399.0, "华东"),
    ("2026-10-02", "李四", "无线鼠标", 10, 89.5, "华南"),
    ("2026-10-03", "王五", "4K 显示器", 2, 1899.0, "华北"),
    ("2026-10-04", "张三", "USB-C 扩展坞", 5, 259.0, "华东"),
    ("2026-10-05", "李四", "机械键盘", 2, 459.0, "华南"),
    ("2026-10-06", "赵六", "无线鼠标", 8, 99.0, "西南"),
    ("2026-10-07", "王五", "4K 显示器", 1, 2099.0, "华北"),
    ("2026-10-08", "张三", "USB-C 扩展坞", 4, 249.0, "华东"),
    ("2026-10-09", "赵六", "机械键盘", 1, 519.0, "西南"),
    ("2026-10-10", "李四", "4K 显示器", 3, 1799.0, "华南"),
]

DIRTY_ROWS = [
    # 3 行关键字段空值
    (None, "张三", "机械键盘", 2, 399.0, "华东"),
    ("2026-10-11", None, "无线鼠标", 6, 89.5, "华南"),
    ("2026-10-12", "王五", "4K 显示器", 2, None, "华北"),
    # 2 行完全重复（与 GOOD_ROWS 首行、末行全同）
    ("2026-10-01", "张三", "机械键盘", 3, 399.0, "华东"),
    ("2026-10-10", "李四", "4K 显示器", 3, 1799.0, "华南"),
    # 2 行数量为负、1 行数量为 0
    ("2026-10-13", "赵六", "无线鼠标", -2, 99.0, "西南"),
    ("2026-10-14", "张三", "机械键盘", -1, 459.0, "华东"),
    ("2026-10-15", "李四", "USB-C 扩展坞", 0, 259.0, "华南"),
    # 1 行数量为非数值文本（pandas 读入为字符串，清洗时会被 numeric 转换剔除）
    ("2026-10-16", "王五", "机械键盘", "十件", 399.0, "华北"),
]


def make(path: str | Path = "sales_raw.xlsx") -> Path:
    rows = GOOD_ROWS + DIRTY_ROWS
    df = pd.DataFrame(rows, columns=COLUMNS)
    path = Path(path)
    df.to_excel(path, index=False)
    print(f"样例数据已生成：{path.resolve()}（共 {len(df)} 行，其中 {len(DIRTY_ROWS)} 行为脏数据）")
    return path


if __name__ == "__main__":
    make()
